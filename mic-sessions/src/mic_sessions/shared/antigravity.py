class TranscriptReader:
    """Reads a JSONL transcript incrementally: each `read()` returns the records completed since the
    previous one (a trailing partial line waits for the next read). A file that shrinks or is replaced
    is read again from the start, and `restarted` says so. Blocking: call it with `asyncio.to_thread`."""

    def __init__(self, path: Path, *, max_bytes: int = 16 * 1024 * 1024) -> None:
        self.path = path
        self._offset = 0
        self._inode: int | None = None
        self._max = max_bytes
        self.restarted = False

    def read(self) -> list[dict[str, Any]]:
        self.restarted = False
        try:
            with self.path.open("rb") as handle:
                status = os.fstat(handle.fileno())
                if self._inode is not None and (status.st_ino != self._inode or status.st_size < self._offset):
                    self._offset = 0
                    self.restarted = True
                self._inode = status.st_ino
                handle.seek(self._offset)
                data = handle.read(self._max)
        except OSError:
            return []
        end = data.rfind(b"\n")
        if end < 0:
            return []
        self._offset += end + 1
        records: list[dict[str, Any]] = []
        for line in data[:end].splitlines():
            with suppress(ValueError):
                record = json.loads(line)
                if isinstance(record, dict):
                    records.append(record)
        return records


def session_logs(home: Path) -> list[Path]:
    """The raw files *Download log* offers, every conversation of the home (cleared ones included):
    `conversations/<id>.db` (SQLite with protobuf payloads, raw only) and its journal files, agy's logs
    (`log/*.log`, Mooi's `--log-file`s among them) and the brain JSONL transcripts (subagents included,
    with `chunks/`)."""
    root = data_dir(home)
    patterns = ("conversations/*.db", "conversations/*.db-wal", "conversations/*.db-shm", "log/*.log",
                "cli.log", "brain/*/.system_generated/logs/*.jsonl", "brain/*/.system_generated/logs/chunks/*")
    files = {path for pattern in patterns for path in root.glob(pattern) if path.is_file() and not path.is_symlink()}
    return sorted(files)


