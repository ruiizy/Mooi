# What agy prints (or logs) once signed in: `Logged in as %s.`, `Successfully authenticated as %s.`,
# `Already authenticated as %s.`, `Print mode: authenticated as %s`, `Headless auth: authenticated as %q`.
_LOGIN_IDENTITY = re.compile(r"\b(?:logged in|authenticated) as\b(.*)", re.IGNORECASE)
_EMAIL = re.compile(r"[A-Za-z0-9._%+'-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")
_LOGIN_OUTPUT_LINES = 64
_LOGIN_LOG_TAIL = 1024 * 1024


class LoginError(AntigravityError):
    """A sign-in that could not complete. `kind` says why, for the caller to pick a status:
    `invalid` (the pasted text is not a code; the attempt stays usable), `rejected` (Google refused the
    code: wrong or expired), `ended` (the helper is gone: cancelled, already used, exited), `timeout`
    and `failed` (agy could not run or store the sign-in)."""

    def __init__(self, kind: str, cause: str, detail: str = "") -> None:
        super().__init__(cause, detail)
        self.kind = kind


def login_url(line: str) -> str | None:
    """The Google authorization URL a line carries, only an `https://accounts.google.com/` one."""
    for candidate in _LOGIN_URL.findall(line):
        candidate = candidate.rstrip(".,;)")
        parsed = urlparse(candidate)
        if parsed.scheme == "https" and parsed.hostname == _LOGIN_HOST and not parsed.username \
                and parsed.port is None and parsed.path.startswith("/o/oauth2/"):
            return candidate
    return None


def login_code(text: str) -> str:
    """The pasted code (or landing URL) as agy reads it: one non-empty line, bounded, no control
    characters. Raises `LoginError("invalid")` otherwise."""
    code = text.strip() if isinstance(text, str) else ""
    if not code:
        raise LoginError("invalid", "Paste the authorization code Google showed you.")
    if len(code) > LOGIN_CODE_LIMIT:
        raise LoginError("invalid", "The authorization code is too long.")
    if any(ord(character) < 32 or ord(character) == 127 for character in code):
        raise LoginError("invalid", "Paste the authorization code on a single line.")
    return code


def login_account(text: str) -> str | None:
    """The signed-in Google email agy reports in `text` (its output or log), or None. Only the address
    is taken: nothing else of the line, and never any token material."""
    for line in text.splitlines():
        match = _LOGIN_IDENTITY.search(line)
        if match and (email := _EMAIL.search(match.group(1))):
            return email.group(0)[:255]
    return None


def _redacted(text: str, *secrets: str) -> str:
    for secret in secrets:
        if secret:
            text = text.replace(secret, "<code>")
    return _LOGIN_URL.sub("<url>", text)[:300]


class Login:
    """agy's own Google sign-in, used as a one-shot helper (`agy acp --login`, never the ACP adapter) in a
    private temporary home, over plain pipes: agy prints the authorization URL on stdout, reads one line
    (the code Google shows, or the full landing URL) from stdin, exits 0 once signed in and, without a
    Secret Service, stores the token as a file in its data directory, captured by `read_credential`.

    `start()` returns the URL; `submit(code)` redeems the code once and returns `(bundle, account)`,
    where `account` is the Google email agy reported (None when it printed none); `close()` ends the
    process and removes the home. The bundle is a secret: never log it. Not reusable after `submit`."""

    def __init__(self, binary: str, *, root: Path | None = None) -> None:
        self._binary = binary
        self._root = root
        self.home: Path | None = None
        self._process: _Process | None = None
        self._reader: asyncio.Task[None] | None = None
        self._url: asyncio.Future[str] | None = None
        self._lines: deque[str] = deque(maxlen=_LOGIN_OUTPUT_LINES)
        self._submitted = False
        self._closed = False

    @property
    def running(self) -> bool:
        return self._process is not None and self._process.running

    async def start(self, timeout: float = LOGIN_START_SECONDS) -> str:
        if self._process is not None or self._closed:
            raise LoginError("ended", "This sign-in already started. Start again.")
        binary = executable(self._binary)
        home = Path(tempfile.mkdtemp(prefix="mooi-agy-login-", dir=self._root))
        self.home = home
        try:
            os.chmod(home, 0o700)
            _private_directory(data_dir(home))
            self._url = asyncio.get_running_loop().create_future()
            # Default data and Gemini directories under `HOME`: exactly where print mode looks later.
            self._process = _Process([binary, "acp", "--login"], cwd=home, env=environment(home))
            spawned = await self._process.spawn()
            assert spawned.stdout is not None
            self._reader = asyncio.create_task(self._read(spawned.stdout))
            try:
                async with asyncio.timeout(timeout):
                    return await asyncio.shield(self._url)
            except TimeoutError:
                raise LoginError("timeout", "Antigravity did not start the Google sign-in in time. Try again.",
                                 self._detail()) from None
        except BaseException:
            await self.close()
            raise

    async def submit(self, code: str, timeout: float = LOGIN_SUBMIT_SECONDS) -> tuple[str, str | None]:
        code = login_code(code)
        process = self._process
        if self._submitted or self._closed or process is None or process.process is None:
            raise LoginError("ended", "This sign-in is no longer active. Start again.")
        if not process.running:
            raise LoginError("ended", "The Google sign-in ended. Start again.", self._detail())
        self._submitted = True
        stdin = process.process.stdin
        assert stdin is not None
        try:
            stdin.write((code + "\n").encode())
            await stdin.drain()
        except (ConnectionError, RuntimeError) as error:
            raise LoginError("ended", "The Google sign-in ended. Start again.", type(error).__name__) from None
        # One code per attempt: a re-prompt after a refused code reads EOF and exits instead of waiting.
        process.close_stdin()
        if not await process.wait(timeout):
            process.signal(signal.SIGTERM)
            raise LoginError("timeout", "The Google sign-in did not finish in time. Start again.", "timeout")
        if self._reader is not None:
            with suppress(TimeoutError, asyncio.CancelledError, Exception):
                await asyncio.wait_for(asyncio.shield(self._reader), 2)
        output = "\n".join([*self._lines, *process.stderr_tail])
        returncode = process.returncode
        if returncode != 0:
            detail = _redacted(self._detail(), code)
            lowered = output.lower()
            if "cancelled" in lowered and "no authorization code" in lowered:
                raise LoginError("ended", "No authorization code reached Antigravity. Start again.", detail)
            if any(word in lowered for word in ("invalid_grant", "invalid", "expired", "malformed", "bad request")):
                raise LoginError("rejected", "Google did not accept this code: it is wrong or has expired. "
                                 "Start the sign-in again.", detail)
            raise LoginError("failed", "Antigravity could not complete the Google sign-in. Try again.", detail)
        assert self.home is not None
        account = login_account(output) or await self._identity()
        try:
            bundle = read_credential(self.home)
        except AntigravityError as error:
            raise LoginError("failed", "Antigravity stored an unusable sign-in. Try again.", error.detail) from None
        if bundle is None:
            raise LoginError("failed", "Antigravity finished the sign-in but stored no credential. Try again.",
                             "no credential file (check CREDENTIAL_FILES)")
        return bundle, account

    async def _identity(self) -> str | None:
        """Best effort when the login printed no address: one `agy -p=/usage` run on the new sign-in (no
        LLM call) and agy's own log of it (`authenticated as …`). Only the email is read."""
        assert self.home is not None
        log_file = _log_file(self.home, "identity")
        try:
            _, _, error = await _run(self._binary, ["-p=/usage", "--output-format", "json", "--log-file",
                                                    str(log_file)],
                                     home=self.home, cwd=None, env=None, timeout=LOGIN_IDENTITY_SECONDS)
        except AntigravityError:
            LOG.debug("Antigravity sign-in identity probe failed", exc_info=True)
            return None
        text = error
        try:
            descriptor = os.open(log_file, os.O_RDONLY | os.O_NOFOLLOW)
            with os.fdopen(descriptor, "rb") as handle:
                size = os.fstat(handle.fileno()).st_size
                handle.seek(max(0, size - _LOGIN_LOG_TAIL))
                text += "\n" + handle.read(_LOGIN_LOG_TAIL).decode("utf-8", "replace")
        except OSError:
            pass
        return login_account(text)

    async def close(self) -> None:
        """Ends the helper (stdin EOF makes agy cancel the login, then its group is terminated) and
        removes the temporary home with whatever it stored. Idempotent."""
        self._closed = True
        if self._url is not None and not self._url.done():
            self._url.cancel()
        if self._process is not None:
            with suppress(Exception):
                await self._process.stop(2)
        if self._reader is not None:
            self._reader.cancel()
            with suppress(asyncio.CancelledError, Exception):
                await self._reader
        if self.home is not None:
            await asyncio.to_thread(shutil.rmtree, self.home, True)

    def _detail(self) -> str:
        return self._process.failure_detail() if self._process else ""

    async def _read(self, stdout: asyncio.StreamReader) -> None:
        url = self._url
        assert url is not None
        try:
            while line := await stdout.readline():
                text = line.decode("utf-8", "replace").rstrip()
                if not text:
                    continue
                if not url.done():
                    if found := login_url(text):
                        url.set_result(found)
                    continue
                self._lines.append(text[:500])
        except (ValueError, asyncio.LimitOverrunError):
            LOG.debug("Antigravity sign-in wrote an oversized line")
        finally:
            if not url.done() and not self._closed:
                process = self._process
                if process is not None:
                    with suppress(Exception):
                        await process.wait(2)
                if not url.done():
                    url.set_exception(LoginError(
                        "failed", "Antigravity could not start the Google sign-in. Try again.",
                        _redacted(self._detail())))
