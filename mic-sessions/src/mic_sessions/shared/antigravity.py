class Stream:
    """One live `agy -p= --input-format stream-json --output-format stream-json` process.

    Turns go in one per stdin line, only after the previous turn's `result` (Mooi's queue stays the only
    queue); events come out as parsed JSON, each `{"event": <kind>, <kind>: {...}}`: `init` (sent on its
    own ~2–7 s after launch, before any input; top-level `conversation_id`, `init.model`, `init.tools`,
    `init.cwd`), `step_update` (`step_update.step_index`, `state`, `step_type`, `text_delta`, `tool_info`,
    `subagent_info`, `usage`) and `result` (one per turn; `result.usage`, `num_turns` and
    `duration_seconds` are cumulative over the conversation). `conversation_id` is known from `init`
    and resumes the conversation in a later process with `conversation_id=`.

    `interrupt()` is a Ctrl-C: the running turn ends with `finished_reason: "interrupted"` and the
    process exits, keeping the conversation for a restart. `close()` closes stdin (agy exits after the
    current turn), waits, then terminates the group. Never log the environment."""

    def __init__(self, binary: str, home: Path, *, cwd: Path, env: Mapping[str, str], model: str | None,
                 effort: str | None, conversation_id: str | None = None) -> None:
        self.home = home
        self.log_file = _log_file(home, "stream")
        self._process = _Process(stream_arguments(binary, home, model=model, effort=effort,
                                                  conversation_id=conversation_id, log_file=self.log_file),
                                 cwd=cwd, env=env)
        self.conversation_id: str | None = conversation_id
        self.init: dict[str, Any] = {}
        self._initialized = asyncio.Event()
        self._events: asyncio.Queue[Any] = asyncio.Queue()
        self._reader: asyncio.Task[None] | None = None
        self._write_lock = asyncio.Lock()
        self._turn_lock = asyncio.Lock()
        self._failure: AntigravityError | None = None
        self._interrupted = False

    @property
    def alive(self) -> bool:
        return self._process.running and self._failure is None

    @property
    def pid(self) -> int | None:
        return self._process.process.pid if self._process.process else None

    @property
    def returncode(self) -> int | None:
        return self._process.returncode

    @property
    def stderr_tail(self) -> list[str]:
        """agy's latest diagnostic lines (soft-deny notices, warnings, the failure reason)."""
        return list(self._process.stderr_tail)

    @property
    def failure(self) -> AntigravityError | None:
        """Why the process stopped serving, once it did."""
        return self._failure

    async def start(self) -> None:
        """Launches the process; `init` follows on its own after a few seconds (`ready()` waits for it)."""
        process = await self._process.spawn()
        assert process.stdout is not None
        self._reader = asyncio.create_task(self._read(process.stdout))

    async def ready(self, timeout: float = 120) -> dict[str, Any]:
        """Waits for the `init` event; a process that exits or stays silent first raises."""
        waiter = asyncio.create_task(self._initialized.wait())
        reader = self._reader
        try:
            pending = {waiter} | ({reader} if reader is not None else set())
            await asyncio.wait(pending, timeout=timeout, return_when=asyncio.FIRST_COMPLETED)
        finally:
            waiter.cancel()
        if self._initialized.is_set():
            return self.init
        if self._failure is not None:
            raise self._failure
        raise AntigravityError("the Antigravity CLI did not start", "no init event")

    async def send(self, text: str) -> None:
        """Writes one user turn. Text only: images go by path (`save_attachment`)."""
        line = json.dumps({"event": "user", "message": {"content": text}}, ensure_ascii=False) + "\n"
        process = self._process.process
        if not self.alive or process is None or process.stdin is None:
            raise self._failure or AntigravityError("the agent process exited")
        async with self._write_lock:
            try:
                process.stdin.write(line.encode())
                await process.stdin.drain()
            except (BrokenPipeError, ConnectionResetError) as error:
                raise AntigravityError("the agent process exited", self._process.failure_detail()) from error

    async def turn(self, text: str) -> AsyncIterator[dict[str, Any]]:
        """Sends one turn and yields every event until its `result` (included). A process that exits
        before the `result` raises `AntigravityError` with the stderr tail as detail."""
        async with self._turn_lock:
            await self.send(text)
            async for event in self.events():
                yield event
                if event.get("event") == "result":
                    return
            raise self._failure or AntigravityError("the agent process exited", self._process.failure_detail())

    async def events(self) -> AsyncIterator[dict[str, Any]]:
        """Events in the order agy wrote them, until the process exits (then the iterator ends; a broken
        stream raises)."""
        while True:
            event = await self._events.get()
            if event is _END:
                self._events.put_nowait(_END)
                if self._failure is not None and self._failure.cause != "the agent process exited":
                    raise self._failure
                return
            yield event

    async def interrupt(self, timeout: float = _INTERRUPT_SECONDS) -> int | None:
        """SIGINT to agy (it kills the running command itself), then waits for the exit; a process that
        does not stop has its group terminated. Returns the exit code (1 after an interrupt)."""
        if not self._process.running:
            return self._process.returncode
        self._interrupted = True
        self._process.signal(signal.SIGINT, group=False)
        if not await self._process.wait(timeout):
            self._process.signal(signal.SIGTERM)
            if not await self._process.wait(_CLOSE_SECONDS):
                self._process.signal(signal.SIGKILL)
        await self._finish_reader()
        return self._process.returncode

    async def close(self, timeout: float = _CLOSE_SECONDS) -> None:
        """Ends the process; safe to call more than once. A turn still running gets `timeout` to finish
        before the group is terminated (an interrupt, for agy)."""
        await self._process.stop(timeout)
        await self._finish_reader()
        self._fail(AntigravityError("the agent process exited", self._process.failure_detail()))

    def failure_detail(self) -> str:
        return self._process.failure_detail()

    async def _finish_reader(self) -> None:
        if self._reader is not None and not self._reader.done():
            with suppress(TimeoutError, asyncio.CancelledError, Exception):
                await asyncio.wait_for(asyncio.shield(self._reader), _CLOSE_SECONDS)
            self._reader.cancel()
            with suppress(asyncio.CancelledError, Exception):
                await self._reader

    async def _read(self, stdout: asyncio.StreamReader) -> None:
        try:
            async for frame in _frames(stdout):
                self._observe(frame)
                self._events.put_nowait(frame)
            await self._process.wait(_CLOSE_SECONDS)
            self._fail(AntigravityError("the agent process exited", self._process.failure_detail()))
        except AntigravityError as error:
            self._fail(error)
        except asyncio.CancelledError:
            self._fail(AntigravityError("the agent process exited", self._process.failure_detail()))
            raise
        except Exception as error:
            self._fail(AntigravityError("the agent stream broke", str(error)))

    def _observe(self, frame: dict[str, Any]) -> None:
        conversation = frame.get("conversation_id")
        if (isinstance(conversation, str) and _CONVERSATION_ID.fullmatch(conversation)
                and (self.conversation_id is None or frame.get("event") == "init")):
            self.conversation_id = conversation
        if frame.get("event") == "init":
            details = frame.get("init")
            self.init = details if isinstance(details, dict) else {}
            self._initialized.set()

    def _fail(self, error: AntigravityError) -> None:
        if self._failure is None:
            self._failure = error
            self._events.put_nowait(_END)


async def _run(binary: str, arguments: Sequence[str], *, home: Path, cwd: Path | None,
               env: Mapping[str, str] | None, timeout: float) -> tuple[int, bytes, str]:
    """One one-shot agy process with stdin closed: `(exit code, stdout, last stderr line)`. A process
    over `timeout` (or a cancelled caller) has its whole group ended."""
    process = _Process([executable(binary), *arguments], cwd=cwd or home, env=env or environment(home))
    spawned = await process.spawn()
    assert spawned.stdout is not None
    process.close_stdin()
    try:
        async with asyncio.timeout(timeout):
            stdout = await spawned.stdout.read()
            code = await spawned.wait()
    except TimeoutError:
        raise AntigravityError("the Antigravity CLI did not answer in time", " ".join(arguments[:1])) from None
    finally:
        await process.stop(1)
    return code, stdout, process.stderr_tail[-1] if process.stderr_tail else ""


def _json_result(stdout: bytes) -> dict[str, Any]:
    """The last JSON object of a `--output-format json` run."""
    for line in reversed(stdout.decode("utf-8", "replace").splitlines()):
        line = line.strip()
        if line.startswith("{"):
            with suppress(ValueError):
                value = json.loads(line)
                if isinstance(value, dict):
                    return value
    with suppress(ValueError):
        value = json.loads(stdout)
        if isinstance(value, dict):
            return value
    return {}


# --- catalog ------------------------------------------------------------------------------------

_catalogs: dict[str, tuple[float, list[dict[str, Any]]]] = {}


def context_window(model: str) -> int | None:
    return next((window for prefix, window in CONTEXT_WINDOWS if model.startswith(prefix)), None)


def parse_models(text: str) -> list[dict[str, Any]]:
    """`agy models` lines (`<base>-<effort>\\t<Label> (<Effort>)`) grouped into base models:
    `{"id", "label", "efforts", "defaultEffort", "contextWindow", "images"}`, in agy's order."""
    models: dict[str, dict[str, Any]] = {}
    for line in text.splitlines():
        identifier, _, label = line.strip().partition("\t")
        if not identifier or not label or any(character.isspace() for character in identifier):
            continue
        base, _, effort = identifier.rpartition("-")
        if effort not in EFFORTS or not base:
            base, effort = identifier, ""
        name = re.sub(r"\s*\((low|medium|high|xhigh|max)\)\s*$", "", label.strip(), flags=re.IGNORECASE)
        entry = models.setdefault(base, {"id": base, "label": name or base, "efforts": [],
                                         "contextWindow": context_window(base),
                                         "images": not base.startswith(_TEXT_ONLY)})
        if effort and effort not in entry["efforts"]:
            entry["efforts"].append(effort)
    for entry in models.values():
        entry["efforts"].sort(key=EFFORTS.index)
        efforts = entry["efforts"]
        entry["defaultEffort"] = DEFAULT_EFFORT if DEFAULT_EFFORT in efforts else (efforts[0] if efforts else None)
    return list(models.values())


async def models(binary: str, home: Path, *, key: str | None = None, env: Mapping[str, str] | None = None,
                 refresh: bool = False, timeout: float = 60) -> list[dict[str, Any]]:
    """The models this account may use, as `agy models` lists them, grouped by base model with their
    efforts. Cached per account (`key`, the connection id) for five minutes. Needs a prepared home
    (the sign-in); no conversation, so it may run while a stream process lives."""
    cached = _catalogs.get(key or "")
    if key and not refresh and cached and cached[0] > time.monotonic():
        return cached[1]
    code, stdout, error = await _run(binary, ["models"], home=home, cwd=None, env=env, timeout=timeout)
    result = parse_models(stdout.decode("utf-8", "replace"))
    if code != 0 or not result:
        raise AntigravityError("the Antigravity models could not be listed", f"exit code {code}; {error}")
    if key:
        for stale, (expires, _) in list(_catalogs.items()):
            if expires < time.monotonic():
                _catalogs.pop(stale, None)
        if len(_catalogs) >= 1024:
            _catalogs.pop(next(iter(_catalogs)))
        _catalogs[key] = (time.monotonic() + 300, result)
    return result


# --- account usage ------------------------------------------------------------------------------

_usages: dict[str, tuple[float, list[dict[str, Any]]]] = {}


def _family(identifier: str) -> str:
    """Which quota family a model or bucket belongs to: agy's own Gemini models or third-party ones."""
    return "gemini" if identifier.startswith("gemini") else "3p"


def _buckets(data: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Flat buckets of a `/usage` result: `{"id", "group", "window", "percent", "resetsAt"}`."""
    groups = ((data.get("command") or {}).get("data") or {}).get("groups") or []
    buckets: list[dict[str, Any]] = []
    for group in groups:
        if not isinstance(group, dict):
            continue
        for bucket in group.get("buckets") or []:
            if not isinstance(bucket, dict) or not isinstance(bucket.get("id"), str):
                continue
            fraction = bucket.get("remaining_fraction")
            if not isinstance(fraction, (int, float)) or isinstance(fraction, bool):
                continue
            reset = bucket.get("reset_time")
            try:
                resets_at = datetime.fromisoformat(reset).timestamp() if reset else None
            except (ValueError, AttributeError):
                resets_at = None
            buckets.append({"id": bucket["id"], "group": str(group.get("name") or bucket["id"]),
                            "window": str(bucket.get("window") or ""),
                            "percent": max(0.0, min(100.0, (1 - float(fraction)) * 100)), "resetsAt": resets_at})
    return buckets


def usage_windows(buckets: Sequence[Mapping[str, Any]], model: str | None = None,
                  updated_at: float | None = None) -> dict[str, Any]:
    """KPI windows in the shape every provider reports (`{"percent", "window", "resetsAt", "updatedAt"}`).

    With `model`, the 5-hour bucket of its quota family is `five_hour` and the most used weekly bucket
    that applies to it (the family's, or a model-specific one such as `Gemini 4 Argon`) is `seven_day`,
    the keys the SPA shows as the session's limits. Every other bucket is kept under a readable key
    (`Claude_and_GPT_models_5h`), shown as an extra row."""
    now = updated_at or time.time()
    windows: dict[str, Any] = {}
    chosen: set[str] = set()
    if model:
        family = [bucket for bucket in buckets if _family(bucket["id"]) == _family(model)
                  and ("argon" not in bucket["id"] or "argon" in model)]
        short = next((bucket for bucket in family if bucket["window"] == "5h"), None)
        weekly = max((bucket for bucket in family if bucket["window"] == "weekly"),
                     key=lambda bucket: bucket["percent"], default=None)
        for name, bucket in (("five_hour", short), ("seven_day", weekly)):
            if bucket is not None:
                chosen.add(bucket["id"])
                windows[name] = {"percent": bucket["percent"], "window": bucket["window"],
                                 "resetsAt": bucket["resetsAt"], "updatedAt": now}
    for bucket in buckets:
        if bucket["id"] in chosen:
            continue
        key = re.sub(r"[^A-Za-z0-9]+", "_", f"{bucket['group']} {bucket['window']}").strip("_")
        windows[key] = {"percent": bucket["percent"], "window": bucket["window"],
                        "resetsAt": bucket["resetsAt"], "updatedAt": now}
    return windows


async def usage(binary: str, home: Path, *, key: str | None = None, model: str | None = None,
                env: Mapping[str, str] | None = None, refresh: bool = False,
                timeout: float = 60) -> dict[str, Any]:
    """The account's 5-hour and weekly limits per model group, as `agy -p=/usage` reads them (no LLM
    call, no conversation: it may run while a stream process lives). Best effort: cached per account
    for a minute, the last reading (or nothing) when agy cannot answer. See `usage_windows`."""
    cached = _usages.get(key or "")
    if key and not refresh and cached and cached[0] > time.monotonic():
        return usage_windows(cached[1], model)
    buckets: list[dict[str, Any]] | None = None
    try:
        code, stdout, _ = await _run(binary, ["-p=/usage", "--output-format", "json"],
                                     home=home, cwd=None, env=env, timeout=timeout)
        result = _json_result(stdout)
        if code == 0 and result.get("status") == "SUCCESS":
            buckets = _buckets(result)
    except AntigravityError:
        LOG.debug("Antigravity account usage is unavailable", exc_info=True)
    if buckets is None:
        LOG.debug("Antigravity account usage is unavailable")
        return usage_windows(cached[1], model) if cached else {}
    if key:
        if len(_usages) >= 1024:
            _usages.pop(next(iter(_usages)))
        _usages[key] = (time.monotonic() + 60, buckets)
    return usage_windows(buckets, model)


