# --- hook bridge --------------------------------------------------------------------------------

# The variable naming the session's hook socket; agy, its hooks and its commands inherit it.
HOOK_SOCKET_VARIABLE = "MOOI_HOOK_SOCKET"
HOOK_NAME = "mooi"
# The question tool: its hook call carries the questions, answered with `deny` + the answer as reason.
QUESTION_TOOL = "ask_question"
# How long agy lets the hook block. Mooi's cards have no timeout of their own (a player may answer
# hours later), so this is the effective limit; the bridge answers `deny` a little before it, so the
# agent always reads Mooi's reason rather than a hook failure.
HOOK_TIMEOUT_SECONDS = 24 * 3600
DECISION_TIMEOUT_SECONDS = HOOK_TIMEOUT_SECONDS - 300
_HOOK_INPUT_LIMIT = 32 * 1024 * 1024
_HOOK_SCRIPT_NAME = "pretooluse_hook.py"
# Run with the service's own interpreter in isolated mode (`-I`): stdlib only, no site or cwd imports.
_HOOK_SCRIPT = '''\
"""Mooi's PreToolUse hook for agy: forwards the hook input to mic-sessions and prints its decision.

Generated by mic-sessions; edits are overwritten. Fails closed: no answer from Mooi denies the action.
"""
import json
import os
import socket
import sys


def main():
    data = sys.stdin.buffer.read()
    path = os.environ.get("@VARIABLE@")
    reply = b""
    if path:
        try:
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as connection:
                connection.connect(path)
                connection.sendall(data)
                connection.shutdown(socket.SHUT_WR)
                chunks = []
                while chunk := connection.recv(65536):
                    chunks.append(chunk)
                reply = b"".join(chunks)
        except OSError:
            reply = b""
    try:
        decision = json.loads(reply)
    except ValueError:
        decision = None
    if not isinstance(decision, dict) or decision.get("decision") not in ("allow", "deny"):
        decision = {"decision": "deny", "reason": "Mooi could not be reached, so the action was not run."}
    sys.stdout.write(json.dumps(decision))
    sys.stdout.flush()


main()
'''.replace("@VARIABLE@", HOOK_SOCKET_VARIABLE)

