class AntigravityError(RuntimeError):
    """The CLI process or its protocol failed; `cause` is a short, user-safe reason and `detail` the
    diagnostic (exit code, last stderr line) for logs."""

    def __init__(self, cause: str, detail: str = "") -> None:
        super().__init__(f"{cause}: {detail}" if detail else cause)
        self.cause = cause
        self.detail = detail


def executable(configured: str) -> str:
    path = shutil.which(configured)
    if path is None:
        raise AntigravityError("the Antigravity CLI is not installed", configured)
    return path


# --- isolation ---------------------------------------------------------------------------------


def _write_private(path: Path, content: str | bytes) -> None:
    """Never through a link planted in the home: the agent can write there too."""
    if path.is_symlink():
        path.unlink()
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(content.encode() if isinstance(content, str) else content)
    os.chmod(path, 0o600)


def _private_directory(path: Path) -> Path:
    if path.is_symlink():
        path.unlink()
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(path, 0o700)
    return path


def data_dir(home: Path) -> Path:
    return home / DATA_DIR


def settings_path(home: Path) -> Path:
    """The session settings passed with `--settings` (print mode never saves them)."""
    return home / MOOI_DIR / "settings.json"


def attachments_dir(home: Path) -> Path:
    """Where the session's images go: outside the repository, readable by rule, named in the prompt."""
    return home / MOOI_DIR / "attachments"


def hook_script(home: Path) -> Path:
    return home / MOOI_DIR / _HOOK_SCRIPT_NAME


def prepare_home(home: Path, credential: Credential, *, instructions: str = "", browser: bool = True,
                 hooks: bool = True) -> None:
    """Writes the private agy home (directories 0700, files 0600). Safe to call again on the same home:
    agy's own state (conversations, transcripts, the renewed sign-in) is kept, Mooi's files rewritten.

    - `.mooi/settings.json`: the allow rules for `--settings`, so headless soft-deny never applies (the
      hook decides), plus `read_file(<attachments>)` for images outside the workspace. No
      `modelProvider` override: only agy's own Google sign-in is used.
    - `.gemini/GEMINI.md`: Mooi's instructions as a global rule (never in the repository).
    - `.gemini/config/hooks.json` + `.mooi/pretooluse_hook.py`: the blocking `PreToolUse` hook on every
      tool, `ask_question` included (`hooks=False` for one-shot homes that run no agent tools).
    - `.gemini/config/mcp_config.json`: the shared Playwright browser (`browser=True`).
    - the credential bundle (`write_credential`)."""
    _private_directory(home)
    for directory in (DATA_DIR, CONFIG_DIR, MOOI_DIR):
        _private_directory(home / directory)
    attachments = _private_directory(attachments_dir(home))
    allow = [*ALLOW_RULES, f"read_file({attachments})"]
    _write_private(settings_path(home), json.dumps({"permissions": {"allow": allow}}, indent=2))
    text = instructions.strip()
    if len(text.encode()) > _INSTRUCTIONS_LIMIT:
        LOG.warning("Antigravity instructions exceed the %s byte rule limit", _INSTRUCTIONS_LIMIT)
    _write_private(home / INSTRUCTIONS_FILE, text + "\n" if text else "")
    hooks_file = home / CONFIG_DIR / "hooks.json"
    if hooks:
        script = hook_script(home)
        _write_private(script, _HOOK_SCRIPT)
        # Run through `sh -c` with the hooks.json directory as cwd: absolute, quoted paths only.
        command = f"{shlex.quote(sys.executable)} -I {shlex.quote(str(script))}"
        _write_private(hooks_file, json.dumps({HOOK_NAME: {"PreToolUse": [{"matcher": "*", "hooks": [
            {"type": "command", "command": command, "timeout": HOOK_TIMEOUT_SECONDS}]}]}}, indent=2))
    else:
        with suppress(FileNotFoundError):
            hooks_file.unlink()
    mcp_file = home / CONFIG_DIR / "mcp_config.json"
    servers: dict[str, Any] = {}
    if browser:
        servers["playwright"] = {**playwright_server(), "disabled": False}
    _write_private(mcp_file, json.dumps({"mcpServers": servers}, indent=2))
    write_credential(home, credential)


def save_attachment(home: Path, data: bytes, suffix: str = ".png") -> Path:
    """Writes one attachment for `read_file` and returns its absolute path, to name in the prompt."""
    clean = suffix if re.fullmatch(r"\.[A-Za-z0-9]{1,8}", suffix) else ""
    path = _private_directory(attachments_dir(home)) / f"{uuid4().hex}{clean}"
    _write_private(path, data)
    return path


def environment(home: Path, extra: Mapping[str, str] | None = None, *,
                hook_socket: str | Path | None = None) -> dict[str, str]:
    """A minimal process environment: the toolchain basics, the session's variables, the private home,
    the hook socket and no self-update. Launched as the whole environment (never merged with the
    service's), so host API keys, proxy credentials and Mooi secrets cannot reach agy, its hooks or the
    commands it runs, which all inherit it. Session variables that would steer agy's sign-in, state or
    backend (`AGY_*`, `ANTIGRAVITY_*`, Gemini/Google keys, `HOME`) are dropped."""
    values = {key: os.environ[key] for key in _INHERITED if key in os.environ}
    dropped = 0
    for key, value in (extra or {}).items():
        if key in _RESERVED or key.startswith(_RESERVED_PREFIXES):
            dropped += 1
            continue
        values[key] = value
    if dropped:
        LOG.debug("Dropped %s session variables reserved for the Antigravity CLI", dropped)
    values.update({
        "HOME": str(home),
        # Exactly `true`: any other spelling is ignored and the binary replaces itself in place.
        "AGY_CLI_DISABLE_AUTO_UPDATE": "true",
        "TERM": "dumb",
    })
    if hook_socket is not None:
        values[HOOK_SOCKET_VARIABLE] = str(hook_socket)
    return values


# --- credential bundle --------------------------------------------------------------------------


def _bundle_path(home: Path, relative: str) -> Path:
    pure = PurePosixPath(relative)
    if (pure.is_absolute() or ".." in pure.parts or not pure.parts
            or pure.parts[:len(DATA_DIR.parts)] != DATA_DIR.parts or len(pure.parts) <= len(DATA_DIR.parts)):
        raise AntigravityError("the Antigravity sign-in is invalid", "bundle path outside the data directory")
    return home.joinpath(*pure.parts)


def write_credential(home: Path, credential: Credential) -> None:
    """Restores agy's sign-in into `home` from the opaque bundle in `credential.token`.

    The bundle is the JSON object `read_credential` produces: `{"<path relative to HOME>": "<base64 of
    the file content>"}`, every path under `.gemini/antigravity-cli/`. Mooi never interprets the files:
    agy owns the Google grant and renews it itself. Listed credential files missing from the bundle are
    removed, so the home holds exactly the bundle's sign-in."""
    if credential.mode != CREDENTIAL_MODE:
        raise AntigravityError("the Antigravity account must be signed in with Google again",
                               f"unsupported credential mode {credential.mode}")
    try:
        bundle = json.loads(credential.token)
    except (TypeError, ValueError) as error:
        raise AntigravityError("the Antigravity sign-in is invalid", "bundle is not JSON") from error
    if not isinstance(bundle, dict) or not bundle:
        raise AntigravityError("the Antigravity sign-in is invalid", "bundle is empty")
    files: dict[Path, bytes] = {}
    for relative, encoded in bundle.items():
        if not isinstance(relative, str) or not isinstance(encoded, str):
            raise AntigravityError("the Antigravity sign-in is invalid", "bundle entries must be strings")
        try:
            content = base64.b64decode(encoded, validate=True)
        except (binascii.Error, ValueError) as error:
            raise AntigravityError("the Antigravity sign-in is invalid", "bundle entry is not base64") from error
        if len(content) > _CREDENTIAL_FILE_LIMIT:
            raise AntigravityError("the Antigravity sign-in is invalid", "bundle entry is too large")
        files[_bundle_path(home, relative)] = content
    for relative in CREDENTIAL_FILES:
        path = _bundle_path(home, relative)
        if path not in files:
            with suppress(FileNotFoundError):
                path.unlink()
    for path, content in files.items():
        _private_directory(path.parent)
        _write_private(path, content)


def read_credential(home: Path) -> str | None:
    """agy's current sign-in in `home` as the opaque bundle `write_credential` restores, or None when no
    credential file exists (never signed in, or signed out). Canonical JSON (sorted keys, no spaces), so
    an unchanged sign-in gives the identical string: compare with `credential.token` to know whether agy
    renewed it and a write-back is due. Never log the result."""
    bundle: dict[str, str] = {}
    root = home.resolve()
    for relative in CREDENTIAL_FILES:
        path = _bundle_path(home, relative)
        # Only a regular file really inside this home: a link the agent planted must never carry
        # another file (another session's sign-in) into this account's write-back.
        if not path.resolve().is_relative_to(root):
            raise AntigravityError("the Antigravity sign-in is invalid", "credential path leaves the home")
        try:
            descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        except FileNotFoundError:
            continue
        except OSError as error:
            raise AntigravityError("the Antigravity sign-in is invalid", "credential file is a link") from error
        with os.fdopen(descriptor, "rb") as handle:
            if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
                raise AntigravityError("the Antigravity sign-in is invalid", "credential path is not a file")
            content = handle.read(_CREDENTIAL_FILE_LIMIT + 1)
        if len(content) > _CREDENTIAL_FILE_LIMIT:
            raise AntigravityError("the Antigravity sign-in is invalid", "credential file is too large")
        bundle[relative] = base64.b64encode(content).decode("ascii")
    return json.dumps(bundle, sort_keys=True, separators=(",", ":")) if bundle else None


# --- hook bridge --------------------------------------------------------------------------------


def allow() -> dict[str, Any]:
    return {"decision": "allow"}


def deny(reason: str) -> dict[str, Any]:
    return {"decision": "deny", "reason": reason}


def answer(text: str) -> dict[str, Any]:
    """The reply to an `ask_question` call: headless agy has no answer channel, so the hook denies the
    tool and the agent reads the reason as the user's answer."""
    return deny(f"The user's answer: {text}")


def tool_call(payload: Mapping[str, Any]) -> tuple[str, dict[str, Any], str | None, int | None]:
    """`(name, args, call id, step index)` of a `PreToolUse` input; args are complete (the stream's
    `tool_info.parameters` are abridged), the step index equals the stream's `step_index`."""
    call = payload.get("toolCall")
    call = call if isinstance(call, dict) else {}
    args = call.get("args")
    step = payload.get("stepIdx")
    return (str(call.get("name") or ""), args if isinstance(args, dict) else {},
            call.get("id") if isinstance(call.get("id"), str) else None,
            step if isinstance(step, int) and not isinstance(step, bool) else None)


def questions(payload: Mapping[str, Any]) -> list[dict[str, Any]] | None:
    """The questions of an `ask_question` call (`{"question", "options", "is_multi_select"}` each), or
    None for any other tool."""
    name, args, _, _ = tool_call(payload)
    if name != QUESTION_TOOL:
        return None
    return [item for item in args.get("questions") or [] if isinstance(item, dict)]


def _decision(value: Any) -> dict[str, Any]:
    """Only what headless agy can act on: `allow`, or `deny` with a reason (it cannot `ask`)."""
    if isinstance(value, dict) and value.get("decision") == "allow":
        return allow()
    reason = value.get("reason") if isinstance(value, dict) else None
    return deny(str(reason) if reason else "The user declined this action")


class HookBridge:
    """The session end of the `PreToolUse` hook: a Unix socket in a private short-path directory (socket
    paths are length-limited, so not inside the home). Each hook process sends agy's hook input and
    half-closes; `handler` decides; the decision is written back and the connection closed. Calls run
    concurrently (agy may run several tools at once), each bounded by `timeout`, after which it is
    denied. `deny_pending` answers every parked call (interrupt, stop); `close` also removes the socket,
    after which hooks fail closed. The socket is reachable by the session's own commands (same user,
    same environment): a call made that way can only raise a card, never answer one."""

    def __init__(self, handler: HookHandler, *, timeout: float = DECISION_TIMEOUT_SECONDS) -> None:
        self._handler = handler
        self._timeout = timeout
        self._server: asyncio.Server | None = None
        self._directory: Path | None = None
        self._pending: set[asyncio.Task[dict[str, Any]]] = set()
        self._connections: set[asyncio.Task[Any]] = set()
        self._closing = False
        self._stop_reason = "The session stopped before the action was approved"

    @property
    def path(self) -> Path:
        if self._directory is None:
            raise AntigravityError("the hook bridge is not started")
        return self._directory / "hook.sock"

    async def start(self) -> Path:
        if self._server is not None:
            return self.path
        self._directory = Path(tempfile.mkdtemp(prefix="mooi-agy-"))
        os.chmod(self._directory, 0o700)
        self._server = await asyncio.start_unix_server(self._serve, path=str(self.path),
                                                       limit=_HOOK_INPUT_LIMIT)
        os.chmod(self.path, 0o600)
        return self.path

    def deny_pending(self, reason: str | None = None) -> None:
        """Answers every call still waiting for the player with `deny`."""
        if reason:
            self._stop_reason = reason
        for task in list(self._pending):
            task.cancel()

    async def close(self) -> None:
        """Stops accepting calls, denies the parked ones and removes the socket. Idempotent."""
        self._closing = True
        self.deny_pending()
        if self._server is not None:
            self._server.close()
        if self._connections:
            await asyncio.wait(set(self._connections), timeout=_CLOSE_SECONDS)
        if self._server is not None:
            with suppress(Exception):
                await asyncio.wait_for(self._server.wait_closed(), _CLOSE_SECONDS)
            self._server = None
        if self._directory is not None:
            shutil.rmtree(self._directory, ignore_errors=True)
            self._directory = None

    async def _serve(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        current = asyncio.current_task()
        if current is not None:
            self._connections.add(current)
        try:
            decision = await self._decide(reader)
            writer.write(json.dumps(decision, ensure_ascii=False).encode())
            with suppress(ConnectionError):
                await writer.drain()
        except Exception:
            LOG.warning("An Antigravity hook call could not be answered", exc_info=True)
        finally:
            writer.close()
            with suppress(Exception):
                await writer.wait_closed()
            if current is not None:
                self._connections.discard(current)

    async def _decide(self, reader: asyncio.StreamReader) -> dict[str, Any]:
        data = bytearray()
        while chunk := await reader.read(65536):
            data += chunk
            if len(data) > _HOOK_INPUT_LIMIT:
                return deny("The action was too large for Mooi to review")
        try:
            payload = json.loads(data)
        except ValueError:
            return deny("Mooi could not read the action")
        if not isinstance(payload, dict):
            return deny("Mooi could not read the action")
        if self._closing:
            return deny(self._stop_reason)
        task = asyncio.create_task(self._handler(payload))
        self._pending.add(task)
        try:
            done, _ = await asyncio.wait({task}, timeout=self._timeout)
            if not done:
                task.cancel()
                return deny("No answer arrived in time, so the action was not run")
            if task.cancelled():
                return deny(self._stop_reason)
            error = task.exception()
            if error is not None:
                LOG.warning("An Antigravity hook decision failed", exc_info=error)
                return deny("Mooi could not decide on this action")
            return _decision(task.result())
        finally:
            self._pending.discard(task)


