"""Antigravity CLI transport: the installed `agy` binary, driven through its print-mode stream-json protocol.

No vendor SDK and no ACP: this module launches the pinned CLI itself as one long-lived process per
session (`agy -p= --input-format stream-json --output-format stream-json`), writes one user turn per
stdin line and reads the `init` / `step_update` / `result` events it prints. Everything print mode
cannot do inside that stream runs as a separate one-shot process on the same private home, never
while a stream process holds the conversation (the caller serialises them): `agy models`,
`agy -p=/usage` and `agy -p=/compact`.

Print mode has a single data-directory knob, `HOME`: every session runs with a private home holding
agy's own state (`.gemini/antigravity-cli/`: sign-in, conversations, logs, brain transcripts), its
global config (`.gemini/config/`: hooks, MCP servers), the global instructions (`.gemini/GEMINI.md`)
and Mooi's own files (`.mooi/`: session settings, the hook script, attachments). The process
environment is minimal, so host keys and Mooi secrets never reach agy or the commands it runs.

Headless agy cannot prompt: actions without an allow rule are soft-denied and questions skipped. So
every action class is allowed by rule, and a blocking `PreToolUse` hook (`HookBridge`) brings Mooi's
permission and question cards back. No application/session contracts live here.
"""
