class _Process:
    """One CLI process in its own process group; closing never leaves its tools, hooks or MCP servers
    behind."""

    def __init__(self, arguments: Sequence[str], *, cwd: Path, env: Mapping[str, str]) -> None:
        self._arguments = list(arguments)
        self._cwd = cwd
        self._env = dict(env)
        self.process: asyncio.subprocess.Process | None = None
        self._stderr: asyncio.Task[None] | None = None
        self.stderr_tail: deque[str] = deque(maxlen=_STDERR_TAIL)

    async def spawn(self) -> asyncio.subprocess.Process:
        try:
            self.process = await asyncio.create_subprocess_exec(
                *self._arguments, cwd=str(self._cwd), env=self._env,
                stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
                limit=_MESSAGE_LIMIT, start_new_session=True,
            )
        except OSError as error:
            raise AntigravityError("the Antigravity CLI could not be started", str(error)) from error
        self._stderr = asyncio.create_task(self._drain_stderr())
        return self.process

    @property
    def running(self) -> bool:
        return self.process is not None and self.process.returncode is None

    @property
    def returncode(self) -> int | None:
        return self.process.returncode if self.process else None

    def signal(self, signum: int, *, group: bool = True) -> None:
        if self.process is None or self.process.returncode is not None:
            return
        with suppress(ProcessLookupError, PermissionError):
            if group:
                os.killpg(self.process.pid, signum)
            else:
                self.process.send_signal(signum)

    def close_stdin(self) -> None:
        process = self.process
        if process is not None and process.stdin is not None and not process.stdin.is_closing():
            with suppress(Exception):
                process.stdin.close()

    async def wait(self, timeout: float) -> bool:
        """Whether the process exited within `timeout`."""
        if self.process is None:
            return True
        try:
            await asyncio.wait_for(self.process.wait(), timeout)
        except TimeoutError:
            return False
        return True

    async def stop(self, timeout: float = _CLOSE_SECONDS) -> None:
        """Closes stdin so agy finishes and saves; one that does not exit has its group terminated, then
        killed."""
        process = self.process
        if process is not None and process.returncode is None:
            self.close_stdin()
            if not await self.wait(timeout):
                self.signal(signal.SIGTERM)
                if not await self.wait(_CLOSE_SECONDS):
                    self.signal(signal.SIGKILL)
                    await process.wait()
        if self._stderr is not None:
            with suppress(TimeoutError, asyncio.CancelledError, Exception):
                await asyncio.wait_for(asyncio.shield(self._stderr), 1)
            self._stderr.cancel()
            with suppress(asyncio.CancelledError, Exception):
                await self._stderr

    def failure_detail(self) -> str:
        code = self.returncode
        return f"exit code {code}" + (f"; {self.stderr_tail[-1]}" if self.stderr_tail else "")

    async def _drain_stderr(self) -> None:
        assert self.process is not None and self.process.stderr is not None
        while line := await self.process.stderr.readline():
            text = line.decode("utf-8", "replace").rstrip()
            if text:
                self.stderr_tail.append(text[:500])
                LOG.debug("Antigravity CLI emitted diagnostic output (%s characters)", len(text))


async def _frames(stream: asyncio.StreamReader) -> AsyncIterator[dict[str, Any]]:
    """Each JSON object agy writes on its own line; anything else (a progress line) is skipped."""
    while True:
        try:
            line = await stream.readline()
        except (ValueError, asyncio.LimitOverrunError) as error:
            raise AntigravityError("an Antigravity message exceeded the size limit") from error
        if not line:
            return
        try:
            frame = json.loads(line)
        except json.JSONDecodeError:
            LOG.debug("Antigravity CLI wrote a non-JSON line (%s bytes)", len(line))
            continue
        if isinstance(frame, dict):
            yield frame


